#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
挂单计件小数修复 —— UPDATE 脚本生成器（带整除闸门）

读取当次生产库查询返回的「小数行」，按商品系数把 qty 还原为真实计件数，
生成带保护条件的 UPDATE 脚本。

安全闸门（不通过则不生成 UPDATE）：
  1. 已整数行（FLOOR(qty)==qty）：跳过，绝不除系数（避免把 1.000 除成 0.909）。
  2. 不能整除行（qty 不是系数的整数倍）：列入人工复核，不进 UPDATE。
  3. 缺系数行：列入人工复核，不进 UPDATE。

用法：
  python gen_fix_sql.py --rows rows.json --coeff 670923:1.1,822931:0.5,808424:1.5 \
                        --wh 1520 --table pos_do_detail --out fix_1520.sql

rows.json 格式（pos_do_detail）：
  [{"id": 24228882, "source_sku_id": "670923", "qty": "1.100"}, ...]
asn_detail 用 sku_id 作为 key：
  [{"id": 1090316, "sku_id": 55628, "qty": "7.500"}, ...]
"""
import argparse
import json
import sys
from decimal import Decimal, ROUND_HALF_UP, getcontext, InvalidOperation

# 默认系数表（source_sku_id / md_sku.id -> 计件系数）
DEFAULT_COEFF = {
    "670923": Decimal("1.1"),
    "822931": Decimal("0.5"),
    "808424": Decimal("1.5"),
}

# 整除判定容差：残差 <= TOL 视为「可被整除」
TOL = Decimal("0.0001")

# 小数精度（qty 列 decimal(10,3) / expt_qty decimal(14,3)）
getcontext().prec = 30


def parse_coeff(spec):
    """解析 '670923:1.1,822931:0.5' 为 {key: Decimal}"""
    coeff = {}
    for part in (spec or "").split(","):
        part = part.strip()
        if not part:
            continue
        if ":" not in part:
            raise ValueError(f"系数格式错误(应为 key:val): {part}")
        k, v = part.split(":", 1)
        try:
            coeff[k.strip()] = Decimal(v.strip())
        except InvalidOperation:
            raise ValueError(f"系数非数值: {part}")
    return coeff


def row_key(row, table):
    """取系数查找键：pos_do_detail 用 source_sku_id，asn_detail 用 sku_id"""
    if table == "asn_detail":
        return str(row.get("sku_id", "")).strip()
    return str(row.get("source_sku_id", "")).strip()


def is_divisible(qty, coef):
    """qty 是否为 coef 的整数倍（残差在容差内）"""
    if coef == 0:
        return False
    ratio = qty / coef
    nearest = ratio.to_integral_value(rounding=ROUND_HALF_UP)
    residue = abs(qty - coef * nearest)
    return residue <= TOL


def main():
    ap = argparse.ArgumentParser(description="挂单计件小数修复 UPDATE 生成器")
    ap.add_argument("--rows", required=True, help="小数行 JSON 文件或 JSON 字符串")
    ap.add_argument("--coeff", default="", help="系数表 key:val,key:val（覆盖默认）")
    ap.add_argument("--wh", default="", help="门店 wh_id（仅用于注释）")
    ap.add_argument("--table", default="pos_do_detail", choices=["pos_do_detail", "asn_detail"])
    ap.add_argument("--out", default="", help="输出 SQL 文件路径（缺省打印到 stdout）")
    args = ap.parse_args()

    # 系数 = 默认 + 覆盖
    coeff = dict(DEFAULT_COEFF)
    coeff.update(parse_coeff(args.coeff))

    # 读取行
    raw = args.rows.strip()
    if raw.startswith("[") or raw.startswith("{"):
        rows = json.loads(raw)
    else:
        with open(raw, "r", encoding="utf-8") as f:
            rows = json.load(f)
    if isinstance(rows, dict):
        rows = rows.get("rows", [])

    clean, dirty, skipped = [], [], []
    for r in rows:
        rid = r.get("id")
        key = row_key(r, args.table)
        try:
            qty = Decimal(str(r.get("qty")))
        except (InvalidOperation, TypeError):
            dirty.append((rid, key, r.get("qty"), None, "qty 非数值"))
            continue
        coef = coeff.get(key)
        if coef is None:
            dirty.append((rid, key, qty, None, "缺系数(未提供该商品系数)"))
            continue
        if qty == qty.to_integral_value(rounding=ROUND_HALF_UP):
            skipped.append((rid, key, qty, coef, "qty 已为整数，跳过以免破坏数据"))
            continue
        if is_divisible(qty, coef):
            new_qty = (qty / coef).to_integral_value(rounding=ROUND_HALF_UP)
            clean.append((rid, key, qty, coef, new_qty))
        else:
            dirty.append((rid, key, qty, coef, f"qty 不能被系数 {coef} 整除"))

    # 生成 SQL
    lines = []
    lines.append("-- ============================================================")
    lines.append("-- 挂单计件小数修复脚本 (auto-generated by pending-order-decimal-fix)")
    lines.append(f"-- 表: {args.table}   门店 wh_id = {args.wh}")
    lines.append("-- 安全闸门: 仅「小数 且 能被系数整除」的行生成 UPDATE；")
    lines.append("--          已整数行 / 不能整除行 / 缺系数行 一律不进 UPDATE。")
    lines.append("-- 生产库执行前请人工复核；本脚本不自动执行任何 DML。")
    lines.append("-- ============================================================")
    lines.append("")
    lines.append(f"-- 通过(生成UPDATE): {len(clean)} 行 | 跳过(已整数): {len(skipped)} 行 | 人工复核: {len(dirty)} 行")
    lines.append("")
    lines.append("-- ---------- 1. 诊断查询（只读，确认现状） ----------")
    if args.table == "pos_do_detail":
        keys = ",".join(sorted({row_key(r, args.table) for r in rows}))
        lines.append(f"select id, wh_id, source_sku_id, qty, do_h_id, del_flag")
        lines.append(f"from pos_do_detail")
        lines.append(f"where wh_id = {args.wh} and source_sku_id in ({keys})")
        lines.append(f"  and qty != FLOOR(qty) and del_flag = 0;")
    else:
        keys = ",".join(sorted({row_key(r, args.table) for r in rows}))
        lines.append(f"select id, wh_id, sku_id, expt_qty, asn_header_id, line_status, del_flag")
        lines.append(f"from asn_detail")
        lines.append(f"where wh_id = {args.wh} and sku_id in ({keys})")
        lines.append(f"  and expt_qty != FLOOR(expt_qty) and del_flag = 0;")
    lines.append("")
    lines.append("-- ---------- 2. 生成的 UPDATE（带保护条件，幂等） ----------")
    if clean:
        for rid, key, qty, coef, new_qty in clean:
            lines.append(f"-- id={rid} source/sku={key}  {qty} / {coef} = {new_qty}")
            lines.append(
                f"update {args.table} t set t.qty = t.qty / {coef}, t.update_date = NOW() "
                f"where t.id = {rid} and t.qty != FLOOR(t.qty) and t.del_flag = 0;"
            )
    else:
        lines.append("-- （无符合闸门条件的行，UPDATE 集为空）")
    lines.append("")
    lines.append("-- ---------- 3. 人工复核清单（不进 UPDATE） ----------")
    if skipped:
        lines.append("-- [已整数-跳过] 这些行当前 qty 已是整数，若直接除系数会破坏数据：")
        for rid, key, qty, coef, note in skipped:
            lines.append(f"--   id={rid} key={key} qty={qty} -> {note}")
    if dirty:
        lines.append("-- [不能整除/缺系数] 需人工确认系数或数据：")
        for rid, key, qty, coef, note in dirty:
            lines.append(f"--   id={rid} key={key} qty={qty} coef={coef} -> {note}")
    if not skipped and not dirty:
        lines.append("-- （无）")
    lines.append("")

    sql = "\n".join(lines)
    if args.out:
        with open(args.out, "w", encoding="utf-8") as f:
            f.write(sql)
        print(f"[OK] 已写出 {args.out}  (clean={len(clean)} skip={len(skipped)} dirty={len(dirty)})", file=sys.stderr)
    else:
        print(sql)


if __name__ == "__main__":
    main()
